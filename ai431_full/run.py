WORKERS=3

def read(path):return json.loads(Path(path).read_text())

def own_code():
    return {p.name:digest(p) for p in sorted(Path(__file__).parent.iterdir()) if p.suffix in ('.py','.md')}

def shared_code():
    return {'gxp_helpers':shared.tools(),'full_helpers':full_code(),'recovery_helpers':recovery_code(),'transport_helpers':transport_code(),'main_study':code_manifest()}

def payload(root):
    base=read(root/'base-config.private.json');q=read(root/'qualification.json');profile=read(root/'provider-profile.json')
    image=capture(['docker','image','inspect','--format','{{.Id}}',base['image']])
    if not q.get('passed') or q.get('clinical_inputs_used') is not False or q.get('image')!=image or q['wrapper_sha256']!=hashlib.sha256(WRAPPER.encode()).hexdigest() or q['export_wrapper_sha256']!=hashlib.sha256(EXPORT_WRAPPER.encode()).hexdigest():raise ValueError('Same-boundary nonclinical qualification required')
    spec=read(root/'inputs/specifications.json');datasets=plan(spec)
    if len(datasets)!=13 or sum(len(d['variables']) for d in datasets)!=531:raise ValueError('Expected complete benchmark')
    return {'architecture':'Independent PharmaSUG AI-431-inspired full-benchmark variable pipeline; not original author software',
        'model':profile['model'],'provider':profile['provider'],'provider_profile':profile,'max_tokens':MAX_TOKENS,'sampling':'Provider defaults; no temperature or reasoning override',
        'plan':datasets,'expected_datasets':[d['dataset'] for d in datasets],'expected_variables':531,'expected_subjects':len(eligible(root/'inputs')),
        'variable_workers':WORKERS,'dataset_workers':1,'max_attempts_per_task':2,'max_attempts_export':2,'provider_automatic_retry':False,
        'variable_system':SYSTEM,'review_system':REVIEW_SYSTEM,'export_system':EXPORT_SYSTEM,'variable_wrapper':WRAPPER,'export_wrapper':EXPORT_WRAPPER,
        'code':own_code(),'shared_code':shared_code(),'image':image,'inputs':manifest(root/'inputs'),'schemas_sha256':digest(root/'source-schemas.json'),'config_sha256':digest(root/'base-config.private.json'),
        'qualification_sha256':digest(root/'qualification.json'),'readiness_sha256':digest(root/'provider-readiness.json'),'source_provenance_sha256':digest(root/'source-provenance.json'),'p21_cache':manifest(Path(base['p21']['cache'])),
        'host_library_versions':{'pandas':pd.__version__,'numpy':np.__version__,'pyreadstat':pyreadstat.__version__},
        'p21_support_inputs':{d:digest(Path(base['inputs'])/'Input'/(d.lower()+'.xpt')) for d in base['p21']['support_domains']},
        'controller_contribution':'ADSL randomized subject keys only; other row universes generated by model. Stable controller row IDs. Independent per-variable code, exact keyed one-to-one merge. No supplied clinical derivations or reference outputs.',
        'review_policy':'Per-dataset advisory review, immutable previously approved specs; never fed to generation workers.',
        'failure_policy':'Exhausted variable blocks its dataset merge; independent variable tasks and unrelated datasets continue. Provider/invalid completion/controller errors stop new requests; in-flight evidence retained. No retry of uncertain API calls. If no provider stop, export accepted dataset subset; complete 13-dataset coverage required for primary P21 score.',
        'adaptation_limits':'Full 13-dataset row-universe contract, fixed attempt cap, automatic QC and no human clinical repairs are benchmark adaptations, not numerical reproduction of authors. No comprehensive row or value oracle.',
        'storage':'Non-cloud unique execution; private full evidence archive with independently verified file hashes. Originals retained.',
        'clinical_rule_changes':False,'P21_feedback':False,'main_study_started':False}

def prepare(root,source,readiness,qualification):
    if root.exists():raise ValueError('Preserve previous root')
    receipt=read(readiness);profile=receipt['profile']
    if not receipt.get('qualified') or profile!=PROFILES[profile['id']]:raise ValueError('Qualified exact provider required')
    root.mkdir(parents=True);shutil.copytree(source/'inputs',root/'inputs')
    for name in ('base-config.private.json','source-schemas.json'):shutil.copy2(source/name,root/name)
    base=read(root/'base-config.private.json');base['inputs']=str(root/'inputs');save(root/'base-config.private.json',base)
    shutil.copy2(readiness,root/'provider-readiness.json');shutil.copy2(qualification,root/'qualification.json')
    save(root/'provider-profile.json',{**profile,'response_model':receipt['response_model']})
    source_lock=read(source/'freeze.json')
    if fingerprint(source_lock['payload'])!=source_lock['sha256'] or manifest(root/'inputs')!=source_lock['payload']['inputs']:raise ValueError('Source input lock/copy mismatch')
    save(root/'source-provenance.json',{'source_freeze_sha256':source_lock['sha256'],'identical_input_manifest':True,'uses_prior_programs_or_results':False})
    frozen=payload(root);save(root/'freeze.json',{'payload':frozen,'sha256':fingerprint(frozen)})
    print('Frozen:',profile['id'],'13 datasets, 531 independent variable tasks, 12 generated row universes',flush=True)

def run(root):
    lock=read(root/'freeze.json');frozen=payload(root)
    if lock!={'payload':frozen,'sha256':fingerprint(frozen)}:raise ValueError('Freeze drift')
    if shutil.disk_usage(root).free<10*1024**3:raise ValueError('Need 10 GiB free before model run')
    out=Path('/private/tmp')/(root.name+'-execution');out.mkdir(exist_ok=False)
    save(root/'run-location.json',{'execution':str(out),'archive':str(root/'run-evidence.tar.gz')});save(out/'plan.json',lock)
    base=read(root/'base-config.private.json');runtime=RebuildRuntime({**base,'inputs':str(root/'inputs')},frozen['image'])
    spec=read(root/'inputs/specifications.json');schemas=read(root/'source-schemas.json');expected=eligible(root/'inputs');datasets=frozen['plan']
    state={'status':'running','started_unix':time.time(),'datasets':{},'tasks':[],'main_study_started':False};mutex=threading.Lock();stop=threading.Event();results={}
    def flush():
        with mutex:save(out/'state.json',state)
    def unchanged():
        if own_code()!=frozen['code'] or shared_code()!=frozen['shared_code'] or manifest(root/'inputs')!=frozen['inputs']:raise ValueError('Frozen code/input drift')
    def generate(prompt,directory,system):
        unchanged()
        if stop.is_set():raise RuntimeError('Stopped; no new model request')
        return request(frozen['provider_profile'],prompt,directory,system,frozen['provider_profile']['response_model'])
    def task(ds,name,seed,keys,definition=None):
        if stop.is_set():return None
        record={'dataset':ds['dataset'],'task':name,'kind':'variable' if definition else 'row_universe','status':'running','attempts':[]};state['tasks'].append(record);flush()
        prompt=json.dumps(context(spec,ds,schemas,definition)|{'row_helpers':[c for c in keys if c.startswith('__SRC_')] if keys is not None else [],'row_count':len(keys) if keys is not None else None},ensure_ascii=False);feedback=''
        for attempt in (1,2):
            if stop.is_set():record['status']='blocked_provider_failure';flush();return None
            directory=out/'datasets'/ds['dataset']/'tasks'/name/f'attempt-{attempt}'
            try:text=generate(prompt+feedback,directory,SYSTEM)
            except Exception as exc:
                stop.set();record.update(status='provider_or_controller_failure',error_type=type(exc).__name__);save(directory/'controller-traceback.private.json',{'traceback':traceback.format_exc()});flush();return None
            workspace=directory/'workspace';shutil.copytree(seed,workspace)
            program='output/adam/programs/variables/'+ds['dataset']+'__'+name+'.py';(workspace/program).write_text(text)
            previous='artifacts/keys.json' if keys is not None else '-';artifact='artifacts/result.json';errors=[];execution=None;frame=None
            try:
                code=shared.extract_code(text);ast.parse(code);(workspace/program).write_text(code);before=manifest(workspace)
                execution=runtime.rebuild(workspace,['python','-B','output/adam/programs/run_variable.py',program,previous,artifact,'artifacts/upstream.json',ds['dataset']],directory/'execution.log',base['rebuild_timeout_seconds'])
                if execution['exit_code'] or execution['timed_out']:raise ValueError('Execution failed: '+(directory/'execution.log').read_text(errors='replace')[-4000:])
                after=manifest(workspace)
                if any(after.get(k)!=v for k,v in before.items()) or set(after)-set(before)!={artifact}:raise ValueError('Protected file modification or undeclared output')
                frame=pd.read_json(workspace/artifact,orient='table');errors=variable_qc(frame,keys,definition) if definition else row_qc(frame,expected)
            except Exception as exc:errors.append(str(exc))
            save(directory/'checks.private.json',{'passed':not errors,'errors':errors,'execution':execution,'missing_count':int(frame[definition['Variable']].isna().sum()) if definition and frame is not None and definition['Variable'] in frame else None})
            record['attempts'].append({'attempt':attempt,'passed':not errors,'program_sha256':digest(workspace/program),'checks_sha256':digest(directory/'checks.private.json'),'usage_sha256':digest(directory/'usage.json')});flush()
            if not errors:
                save(directory/'workspace-manifest.json',manifest(workspace));record.update(status='passed',accepted_attempt=attempt);flush();print(ds['dataset']+'.'+name+': passed attempt '+str(attempt),flush=True)
                return {'workspace':workspace,'program':program,'frame':frame}
            feedback='\nPrevious complete response:\n'+text+'\nExecution/QC errors:\n'+json.dumps(errors)+'\nReturn one corrected complete Python module for the same independent task.'
        record['status']='failed';flush();print(ds['dataset']+'.'+name+': exhausted two attempts',flush=True);return None
    flush()
    try:
        for ds in datasets:
            name=ds['dataset']
            if stop.is_set():state['datasets'][name]={'status':'blocked_provider_failure'};flush();continue
            if not all(dep in results for dep in ds['dependencies']):state['datasets'][name]={'status':'blocked_dependency'};flush();continue
            state['datasets'][name]={'status':'running'};flush()
            advisory=generate(json.dumps({'dataset':ds['metadata'],'variables':ds['variables'],'rules':spec['sheets']['Rules'],'source_schemas':schemas},ensure_ascii=False),out/'reviews'/name,REVIEW_SYSTEM)
            save(out/'reviews'/name/'advisory.private.json',{'text':advisory,'applied_to_specification':False,'fed_to_variable_workers':False})
            seed=out/'datasets'/name/'seed';(seed/'artifacts/upstream').mkdir(parents=True);(seed/'output/adam/programs/variables').mkdir(parents=True)
            (seed/'output/adam/programs/run_variable.py').write_text(WRAPPER);up={}
            for dep in ds['dependencies']:
                path='artifacts/upstream/'+dep+'.json';results[dep]['frame'].to_json(seed/path,orient='table',index=False,double_precision=15);up[dep]=path
            save(seed/'artifacts/upstream.json',up);universe=None
            if name=='ADSL':
                keys=expected[['USUBJID']].copy();keys['__ROWID']=list(range(len(keys)))
            else:
                universe=task(ds,'row_universe',seed,None)
                if universe is None:state['datasets'][name]={'status':'provider_or_controller_failure' if stop.is_set() else 'failed_row_universe'};flush();continue
                keys=universe['frame']
            keys.to_json(seed/'artifacts/keys.json',orient='table',index=False,double_precision=15)
            accepted={}
            with ThreadPoolExecutor(max_workers=WORKERS) as pool:
                futures={pool.submit(task,ds,v['Variable'],seed,keys,v):v['Variable'] for v in ds['variables']}
                for future in as_completed(futures):
                    variable=futures[future]
                    try:value=future.result()
                    except Exception as exc:
                        stop.set();save(out/'datasets'/name/(variable+'-unexpected.private.json'),{'type':type(exc).__name__,'traceback':traceback.format_exc()});value=None
                    if value is not None:accepted[variable]=value
            if len(accepted)!=len(ds['variables']):state['datasets'][name]={'status':'provider_or_controller_failure' if stop.is_set() else 'failed_variables','passed_variables':len(accepted),'expected_variables':len(ds['variables'])};flush();continue
            merged=merge_variables(keys,{k:r['frame'] for k,r in accepted.items()},ds['variables']);defs={v['Variable']:v for v in ds['variables']}
            errors=node_checks(merged,None,set(defs),defs,expected,set(defs),name);save(out/'datasets'/name/'merge-checks.private.json',{'passed':not errors,'errors':errors})
            if errors:state['datasets'][name]={'status':'failed_merge_qc'};flush();continue
            results[name]={'frame':merged[list(defs)].copy(),'variables':accepted,'universe':universe};state['datasets'][name]={'status':'passed','rows':len(merged),'passed_variables':len(accepted)};flush()
        if stop.is_set():raise RuntimeError('Provider/completion/controller failure; no further requests')
        if not results:raise RuntimeError('No complete dataset accepted; export blocked')
        seed=out/'export-seed';(seed/'artifacts').mkdir(parents=True);(seed/'output/adam/programs/variables').mkdir(parents=True)
        (seed/'output/adam/programs/run_variable.py').write_text(WRAPPER);(seed/'output/adam/programs/run_export.py').write_text(EXPORT_WRAPPER)
        frames={};paths={}
        for name,result in results.items():
            frames[name]=result['frame'];path='artifacts/'+name+'-final.json';frames[name].to_json(seed/path,orient='table',index=False,double_precision=15);paths[name]=path
            programs=list(result['variables'].values())+([result['universe']] if result['universe'] else [])
            for value in programs:shutil.copy2(value['workspace']/value['program'],seed/value['program'])
        save(seed/'artifacts/datasets.json',paths)
        prompt=json.dumps({'task':'export','accepted_datasets':list(frames),'metadata_source':'/inputs/specifications.json','expected_dataset_files':[k.lower()+'.xpt' for k in frames],'frame_schemas':{k:{c:str(v) for c,v in f.dtypes.items()} for k,f in frames.items()},'contract':'Preserve all values, no clinical derivations; exact delivery paths as system instructions.'});feedback='';final=None
        export={'status':'running','attempts':[]};state['export']=export;flush()
        for attempt in (1,2):
            directory=out/'export'/f'attempt-{attempt}';text=generate(prompt+feedback,directory,EXPORT_SYSTEM);workspace=directory/'workspace';shutil.copytree(seed,workspace);program=workspace/'output/adam/programs/export.py';program.write_text(text);errors=[];coverage={};execution=None
            try:
                code=shared.extract_code(text);ast.parse(code);program.write_text(code);before=manifest(workspace)
                execution=runtime.rebuild(workspace,['python','-B','output/adam/programs/run_export.py'],directory/'execution.log',base['rebuild_timeout_seconds'])
                if execution['exit_code'] or execution['timed_out']:raise ValueError('Export execution failed: '+(directory/'execution.log').read_text(errors='replace')[-4000:])
                after=manifest(workspace)
                if any(after.get(k)!=v for k,v in before.items()):raise ValueError('Protected programs/artifacts changed')
                coverage,errors=export_checks(workspace,spec,frames)
            except Exception as exc:errors.append(str(exc))
            save(directory/'checks.private.json',{'passed':not errors,'errors':errors,'coverage':coverage,'execution':execution})
            export['attempts'].append({'attempt':attempt,'passed':not errors,'program_sha256':digest(program),'usage_sha256':digest(directory/'usage.json'),'checks_sha256':digest(directory/'checks.private.json')});flush()
            if not errors:
                save(directory/'workspace-manifest.json',manifest(workspace));final=workspace;export.update(status='passed',accepted_attempt=attempt);flush();break
            feedback='\nPrevious response:\n'+text+'\nExport errors:\n'+json.dumps(errors)+'\nReturn corrected complete compact source; no clinical changes.'
        if final is None:export['status']='failed';raise RuntimeError('Combined export exhausted two attempts')
        package=out/'final-workspace';shutil.copytree(final,package);(package/'output/adam/programs/rebuild.py').write_text(replay_entry(datasets,set(results)));before=manifest(package);save(out/'final-workspace-manifest.json',before)
        (out/'final-evaluation').mkdir()
        evaluation=Evaluator(base,frozen['image'])(package,out/'final-evaluation')
        if manifest(package)!=before:raise RuntimeError('Evaluator altered final package')
        save(out/'evaluation.private.json',evaluation);state['status']='completed' if len(results)==13 else 'completed_partial'
    except BaseException as exc:
        state.update(status='failed',error_type=type(exc).__name__,reason=str(exc));save(out/'failure-traceback.private.json',{'traceback':traceback.format_exc()});raise
    finally:
        state['finished_unix']=time.time();flush();archive_evidence(out,root)

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('action',choices=['prepare-freeze','run']);p.add_argument('--root',type=Path,required=True);p.add_argument('--source',type=Path);p.add_argument('--readiness',type=Path);p.add_argument('--qualification',type=Path);p.add_argument('--env-file',type=Path,required=True);p.add_argument('--execute',action='store_true');a=p.parse_args();load_env(a.env_file)
    if a.action=='prepare-freeze':
        if not all((a.source,a.readiness,a.qualification)):p.error('Source, readiness and qualification required')
        prepare(a.root,a.source,a.readiness,a.qualification)
    else:
        if not a.execute:p.error('--execute required')
        run(a.root)

if __name__=='__main__':main()
